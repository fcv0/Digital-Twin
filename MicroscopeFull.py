class ActivitySpinner(QWidget):
    """Small rotating arc that proves the UI thread is still alive."""

    def __init__(self, size: int = 14, color: str = GREEN, parent=None):
        super().__init__(parent)
        self._angle  = 0
        self._color  = color
        self._active = False
        self.setFixedSize(size, size)
        self._timer = QTimer(self)
        self._timer.setInterval(80)
        self._timer.timeout.connect(self._tick)

    def start(self):
        self._active = True
        self._timer.start()
        self.show()

    def stop(self):
        self._active = False
        self._timer.stop()
        self.hide()

    def _tick(self):
        self._angle = (self._angle + 30) % 360
        self.update()

    def paintEvent(self, event):
        if not self._active:
            return
        p = QPainter(self)
        p.setRenderHint(QPainter.RenderHint.Antialiasing)
        pen = QPen(QColor(self._color), 2.5, Qt.PenStyle.SolidLine, Qt.PenCapStyle.RoundCap)
        p.setPen(pen)
        p.setBrush(Qt.BrushStyle.NoBrush)
        m = 2
        rect = QRectF(m, m, self.width() - 2 * m, self.height() - 2 * m)
        # Draw a 270° arc (leaving a 90° gap) starting at the current angle
        p.drawArc(rect, self._angle * 16, 270 * 16)


class ImageView(QWidget):
    def __init__(self):
        super().__init__()
        self._arr          = None
        self.auto_contrast = True
        self.setMinimumSize(480, 480)
        self.setSizePolicy(QSizePolicy.Policy.Expanding, QSizePolicy.Policy.Expanding)
        self.setStyleSheet(f"background-color: {PANEL}; border-radius: 8px;")

    def set_image(self, arr: np.ndarray):
        self._arr = arr
        self.update()

    def paintEvent(self, event):
        p = QPainter(self)
        p.setRenderHint(QPainter.RenderHint.SmoothPixmapTransform)

        if self._arr is None:
            p.setPen(QColor(MUTED))
            p.setFont(QFont("Segoe UI", 13))
            p.drawText(self.rect(), Qt.AlignmentFlag.AlignCenter, "No image\n\nSnap or start Live")
            return

        arr = self._arr.astype(np.float32)
        if self.auto_contrast:
            lo = np.percentile(arr, 0.5)
            hi = np.percentile(arr, 99.5)
            arr = np.clip((arr - lo) / max(hi - lo, 1) * 255, 0, 255).astype(np.uint8)
        else:
            arr = np.clip(arr / max(arr.max(), 1) * 255, 0, 255).astype(np.uint8)

        h, w = arr.shape
        qi  = QImage(arr.data, w, h, w, QImage.Format.Format_Grayscale8)
        pix = QPixmap.fromImage(qi).scaled(self.size(), Qt.AspectRatioMode.KeepAspectRatio, Qt.TransformationMode.SmoothTransformation)
        p.drawPixmap(
            (self.width()  - pix.width())  // 2,
            (self.height() - pix.height()) // 2,
            pix,
        )


