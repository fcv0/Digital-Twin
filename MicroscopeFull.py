    # ── Slots ─────────────────────────────────────────────────────────────────

    def _toggle(self):
        if self._worker and self._worker.isRunning():
            self._stop()
        else:
            self._run()

    def _run(self):
        try:
            current_z = self.scope.get_z()
        except Exception as e:
            self._status.setText(f"Error reading Z: {e}")
            self._status.setStyleSheet(f"color: {RED};")
            return

        half   = self._range.value()
        z_step = self._step.value()
        z_start = current_z - half
        z_end   = current_z + half

        self._total_steps = max(1, int((z_end - z_start) / z_step) + 1)
        self._curve.reset()
        self._progress.setValue(0)
        self._status.setText("Scanning...")
        self._status.setStyleSheet(f"color: {YELLOW};")
        self._best_lbl.setText("Best Z: —")
        self._btn.setText("Stop")
        self._btn.setStyleSheet(f"""
            QPushButton {{
                background-color: {RED}; color: {PANEL};
                border: none; border-radius: 6px;
                padding: 5px 14px; font-weight: 600;
            }}
            QPushButton:hover {{ background-color: {RED}cc; }}
        """)

        self.sig_started.emit()
        self._worker = AutofocusWorker(
            self.scope, z_start, z_end, z_step, self._settle.value(),
            two_pass=self._two_pass_cb.isChecked()
        )
        self._worker.total_steps.connect(self._on_total_steps)
        self._worker.progress.connect(self._on_progress)
        self._worker.frame.connect(self.sig_frame.emit)
        self._worker.finished.connect(self._on_finished)
        self._worker.aborted.connect(self._on_aborted)
        self._worker.err.connect(self._on_af_err)
        self._worker.start()

    def _stop(self):
        if self._worker:
            self._worker.stop()

    def _on_total_steps(self, n: int):
        self._total_steps = max(1, n)

    def _on_progress(self, idx: int, z: float, score: float, phase: str):
        self._curve.add_point(z, score, phase)
        pct = int((idx + 1) / self._total_steps * 100)
        self._progress.setValue(min(pct, 99))
        label = "Coarse" if phase == "coarse" else "Fine"
        self._status.setText(f"{label}  Z: {z:.2f} µm")

    def _on_finished(self, best_z: float, best_score: float):
        self._curve.mark_best_z(best_z)
        self._progress.setValue(100)
        self._status.setText("Done — sub-step precision applied")
        self._status.setStyleSheet(f"color: {GREEN};")
        self._best_lbl.setText(f"Best Z: {best_z:.3f} µm")
        self.sig_best_z.emit(best_z)
        self._reset_btn()

    def _on_af_err(self, msg: str):
        self._status.setText("Error — see Logs tab")
        self._status.setStyleSheet(f"color: {RED};")
        self.sig_log.emit(msg)

    def _on_aborted(self):
        # If the status already shows an error from _on_af_err, preserve it
        if self._status.styleSheet() != f"color: {RED};":
            self._status.setText("Aborted — no valid images acquired")
            self._status.setStyleSheet(f"color: {MUTED};")
        self._reset_btn()

    def _reset_btn(self):
        self.sig_stopped.emit()
        self._btn.setText("Run Autofocus")
        self._btn.setStyleSheet(f"""
            QPushButton {{
                background-color: {GREEN}; color: {PANEL};
                border: none; border-radius: 6px;
                padding: 5px 14px; font-weight: 600;
            }}
            QPushButton:hover {{ background-color: {GREEN}cc; }}
        """)

    # ── Focus Stack ───────────────────────────────────────────────────────────

    def _fs_toggle(self):
        if self._fs_worker and self._fs_worker.isRunning():
            self._fs_worker.stop()
        else:
            self._fs_run()

    def _fs_run(self):
        if self._worker and self._worker.isRunning():
            return   # don't start while AF is running

        current_z = self.scope.get_z()
        half      = self._range.value()
        z_step    = self._step.value()
        n         = int(self._fs_grid.currentText().split()[0])
        grid      = (n, n)

        self._fs_stat.setText("Acquiring Z-stack...")
        self._fs_stat.setStyleSheet(f"color: {YELLOW}; font-size: 11px; background: transparent;")
        self._progress.setValue(0)
        self._fs_btn.setText("Stop")
        self._fs_btn.setStyleSheet(f"""
            QPushButton {{
                background-color: {RED}; color: {PANEL};
                border: none; border-radius: 6px;
                padding: 5px 14px; font-weight: 600;
            }}
            QPushButton:hover {{ background-color: {RED}cc; }}
        """)

        self._fs_worker = FocusStackWorker(
            self.scope,
            current_z - half, current_z + half,
            z_step, self._settle.value(), grid
        )
        self._fs_worker.progress.connect(self._fs_on_progress)
        self._fs_worker.finished.connect(self._fs_on_finished)
        self._fs_worker.aborted.connect(self._fs_on_aborted)
        self._fs_worker.start()

    def _fs_on_progress(self, done: int, total: int):
        self._progress.setValue(int(done / total * 100))
        self._fs_stat.setText(f"Slice {done}/{total}")

    def _fs_on_finished(self, composite: np.ndarray, median_z: float, best_z):
        self._progress.setValue(100)
        n = int(self._fs_grid.currentText().split()[0])
        self._fs_stat.setText(
            f"Done — {n}×{n} composite  ·  stage → {median_z:.3f} µm"
        )
        self._fs_stat.setStyleSheet(f"color: {CYAN}; font-size: 11px; background: transparent;")
        self._quadrant_zs = best_z
        self.sig_composite.emit(composite)
        self.sig_best_z.emit(median_z)
        self.sig_quadrant_zs.emit(best_z)
        self._fs_reset_btn()

    def _fs_on_aborted(self):
        self._fs_stat.setText("Aborted")
        self._fs_stat.setStyleSheet(f"color: {MUTED}; font-size: 11px; background: transparent;")
        self._fs_reset_btn()

    def _fs_reset_btn(self):
        self._fs_btn.setText("Run Focus Stack")
        self._fs_btn.setStyleSheet(f"""
            QPushButton {{
                background-color: {CYAN}; color: {PANEL};
                border: none; border-radius: 6px;
                padding: 5px 14px; font-weight: 600;
            }}
            QPushButton:hover {{ background-color: {CYAN}cc; }}
        """)


