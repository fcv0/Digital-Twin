class MicroscopeInterface:
    X_STAGE = "SCC201_40331924-1"  # Thorlabs linear stage
    Z_STAGE = "Cairn Z Act"        # Cairn focus actuator

    def __init__(self):
        self.core = None
        self.connected = False
        self._dx = 0.0   # demo position
        self._dz = 50.0

    def connect(self):
        if not _MM_AVAILABLE:
            raise RuntimeError(
                "pycromanager not installed.\n"
                "Run: pip install pycromanager\n"
                "Then start Micro-Manager 2.0 with the pycromanager plugin running."
            )
        self.core = Core()
        self.connected = True

    def disconnect(self):
        self.core = None
        self.connected = False

    # ── Stage ─────────────────────────────────────────────────────────────────

    def get_x(self):
        return self.core.get_position(self.X_STAGE) if self.connected else self._dx

    def get_y(self):
        """Returns Y position (µm) or float('nan') if the rig has no Y stage."""
        if not self.connected:
            return float("nan")
        try:
            return float(self.core.get_y_position())
        except Exception:
            return float("nan")

    def get_z(self):
        return self.core.get_position() if self.connected else self._dz

    def set_x(self, value: float):
        if self.connected:
            self.core.set_position(self.X_STAGE, float(value))
            self.core.wait_for_device(self.X_STAGE)
        else:
            self._dx = value

    def set_z(self, value: float):
        if self.connected:
            self.core.set_position(float(value))
            self.core.wait_for_device(self.Z_STAGE)
        else:
            self._dz = value

    # Maximum distance allowed per single relative move click (µm).
    # Prevents a mis-typed step value from sending the stage across the full range.
    MAX_MOVE_UM = 2000.0

    def move_x_rel(self, delta: float):
        delta = float(delta)
        if abs(delta) > self.MAX_MOVE_UM:
            raise ValueError(
                f"Requested X move {delta:.1f} µm exceeds safety limit "
                f"({self.MAX_MOVE_UM} µm). Edit MAX_MOVE_UM if intentional."
            )
        if self.connected:
            self.core.set_relative_position(self.X_STAGE, delta)
            self.core.wait_for_device(self.X_STAGE)
        else:
            self._dx += delta

    def move_z_rel(self, delta: float):
        delta = float(delta)
        if abs(delta) > self.MAX_MOVE_UM:
            raise ValueError(
                f"Requested Z move {delta:.1f} µm exceeds safety limit "
                f"({self.MAX_MOVE_UM} µm). Edit MAX_MOVE_UM if intentional."
            )
        if self.connected:
            self.core.set_relative_position(self.Z_STAGE, delta)
            self.core.wait_for_device(self.Z_STAGE)
        else:
            self._dz += delta

    # ── Camera ────────────────────────────────────────────────────────────────

    def snap(self) -> np.ndarray:
        if self.connected:
            # Stop any running sequence acquisition before snapping.
            # Live mode uses continuous sequence acquisition; if it was
            # recently stopped, the camera may still be flagged as busy.
            try:
                if self.core.is_sequence_running():
                    self.core.stop_sequence_acquisition()
                    for _ in range(40):          # wait up to 2 s in 50 ms steps
                        time.sleep(0.05)
                        if not self.core.is_sequence_running():
                            break
            except Exception:
                pass
            self.core.snap_image()
            t = self.core.get_tagged_image()
            return np.reshape(t.pix, [t.tags["Height"], t.tags["Width"]])
        rng = np.random.default_rng()
        img = rng.integers(200, 800, (512, 512), dtype=np.uint16)
        cy = 256 + int(self._dz) % 128
        cx = 256 + int(self._dx / 10) % 128
        y, x = np.ogrid[:512, :512]
        img = (img + 3000 * np.exp(-((x - cx) ** 2 + (y - cy) ** 2) / (2 * 30 ** 2))).astype(np.uint16)
        return img

    def set_exposure(self, ms: int):
        if self.connected:
            self.core.set_exposure(ms)

    def set_binning(self, value: str):
        if self.connected:
            self.core.set_property("CellCam", "Binning", str(value))

    # ── Illumination ──────────────────────────────────────────────────────────

    def set_channel(self, channel: str):
        if self.connected:
            self.core.set_config("Channels", channel)

    def set_channel_off(self):
        if self.connected:
            for prop in ["Direct Digital Out_P0.0", "Direct Digital Out_P0.1",
                         "Direct Digital Out_P0.2", "Direct Digital Out_P1.0",
                         "Direct Digital Out_P1.1"]:
                self.core.set_property("CairnNI", prop, "0")

    def set_yfp_intensity(self, percent: int):
        if self.connected:
            self.core.set_property("CairnNI", "Direct Analogue Out 1", str(percent / 100 * 5.0))

    def set_phase_intensity(self, percent: int):
        if self.connected:
            self.core.set_property("CairnNI", "Direct Analogue Out 0", str(percent / 100 * 5.0))

    def set_channel_full(self, preset: str, source: str, power: int, exposure: int):
        """Apply a full channel definition: exposure → intensity → preset."""
        self.set_exposure(exposure)
        if source == "LED":
            if preset == "YFP":
                self.set_yfp_intensity(power)
            else:
                self.set_phase_intensity(power)
        self.set_channel(preset)


