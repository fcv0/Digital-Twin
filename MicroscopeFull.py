class AcquisitionWorker(QThread):
    progress = pyqtSignal(int, int, str, str)  # imgs_done, total, fov_name, channel
    frame    = pyqtSignal(object)              # np.ndarray for live preview
    done     = pyqtSignal(int)                 # total images saved
    err      = pyqtSignal(str)

    def __init__(self, scope, timepoints: int, interval_s: float,
                 fovs: list, channels: list, base_z: float, out_dir: str,
                 zstack: dict | None = None, autofocus: dict | None = None,
                 quadrant_zs=None, periodic_channels: list | None = None):
        super().__init__()
        self.scope             = scope
        self.timepoints        = timepoints
        self.interval_s        = interval_s
        self.fovs              = fovs
        self.channels          = channels
        self.base_z            = base_z
        self.out_dir           = out_dir
        self.zstack            = zstack           # None or {'range': float, 'step': float}
        self.autofocus         = autofocus        # None or {'range', 'step', 'settle', 'adaptive'}
        self.quadrant_zs       = quadrant_zs      # None or ndarray (rows×cols)
        self.periodic_channels = periodic_channels or []
        self._active           = True

        enabled  = [f for f in fovs if f["enabled"]]
        if quadrant_zs is not None:
            n_slices = int(quadrant_zs.size)
        else:
            n_slices = (max(1, int(zstack["range"] * 2 / zstack["step"]) + 1)
                        if zstack else 1)
        n_periodic = sum(
            math.ceil(timepoints / max(1, p["every_n"]))
            for p in self.periodic_channels
        )
        self._total = timepoints * len(enabled) * len(channels) * n_slices + \
                      n_periodic * len(enabled)

    def _snap_tiled(self, quad_zs) -> tuple:
        """
        Snap once per quadrant at its best-Z, return (stitched_image, snap_count).
        quad_zs is a (rows x cols) ndarray of Z positions.
        """
        rows, cols = quad_zs.shape
        crops = {}
        img_shape = None
        snaps = 0
        for r in range(rows):
            for c in range(cols):
                if not self._active:
                    return None, snaps
                self.scope.set_z(float(quad_zs[r, c]))
                self.msleep(80)
                full = self.scope.snap()
                snaps += 1
                if img_shape is None:
                    img_shape = full.shape
                H, W = img_shape
                qh = H // rows
                qw = W // cols
                y0, y1 = r * qh, min((r + 1) * qh, H)
                x0, x1 = c * qw, min((c + 1) * qw, W)
                crops[(r, c)] = full[y0:y1, x0:x1]

        H, W = img_shape
        qh = H // rows
        qw = W // cols
        out = np.zeros((H, W), dtype=next(iter(crops.values())).dtype)
        for r in range(rows):
            for c in range(cols):
                y0, y1 = r * qh, min((r + 1) * qh, H)
                x0, x1 = c * qw, min((c + 1) * qw, W)
                out[y0:y1, x0:x1] = crops[(r, c)]
        return out, snaps

    def run(self):
        os.makedirs(self.out_dir, exist_ok=True)
        count     = 0
        t_start   = time.time()
        af_last_z = self.base_z
        af_range  = self.autofocus["range"] if self.autofocus else 0.0

        for t_idx in range(self.timepoints):
            if not self._active:
                break

            # Wait until this timepoint is due, checking for abort every 100 ms
            due = t_start + t_idx * self.interval_s
            while time.time() < due and self._active:
                self.msleep(100)

            if not self._active:
                break

            # Per-timepoint autofocus — updates t_base_z for this timepoint's FOVs
            t_base_z = self.base_z
            if self.autofocus and self._active:
                try:
                    center_z = self.scope.get_z()
                    new_z    = self._inline_autofocus(center_z, af_range)
                    if new_z is not None:
                        if self.autofocus.get("adaptive") and t_idx > 0:
                            drift    = abs(new_z - af_last_z)
                            af_range = max(self.autofocus["step"] * 3,
                                           min(drift * 3.0, self.autofocus["range"]))
                            self.err.emit(
                                f"T{t_idx}: AF drift {drift:.2f} µm → range ±{af_range:.1f} µm"
                            )
                        af_last_z = new_z
                        t_base_z  = new_z
                except Exception as e:
                    self.err.emit(f"T{t_idx} autofocus failed: {e}")

            for fov in self.fovs:
                if not fov["enabled"] or not self._active:
                    continue
                try:
                    self.scope.set_x(fov["x"])
                    self.scope.set_z(t_base_z + fov["z_offset"])
                    self.msleep(200)
                except Exception as e:
                    self.err.emit(f"Stage error at {fov['name']}: {e}")
                    continue

                for ch in self.channels:
                    if not self._active:
                        break

                    fov_z   = t_base_z + fov["z_offset"]
                    ch_name = ch["name"]

                    # Build Z positions — single slice if Z-stack disabled
                    if self.zstack:
                        half        = self.zstack["range"]
                        step        = self.zstack["step"]
                        z_positions = list(np.arange(fov_z - half,
                                                      fov_z + half + step * 0.5,
                                                      step))
                    else:
                        z_positions = [fov_z]

                    # Power: ramp if power_end set, then per-FOV YFP override
                    power_start = ch["power"]
                    power_end   = ch.get("power_end", 0)
                    if power_end > 0 and power_end != power_start:
                        frac     = t_idx / max(self.timepoints - 1, 1)
                        ch_power = int(round(power_start + (power_end - power_start) * frac))
                    else:
                        ch_power = power_start
                    if ch["preset"] == "YFP" and fov.get("yfp_power", 0) > 0:
                        ch_power = fov["yfp_power"]

                    try:
                        self.scope.set_channel_full(
                            ch["preset"], ch["source"], ch_power, ch["exposure"]
                        )
                        self.msleep(50)
                    except Exception as e:
                        self.err.emit(f"Channel error {ch_name}: {e}")
                        continue

                    # Base metadata shared by all snaps at this channel/FOV/timepoint
                    ch_meta_base = {
                        "fov_name":           fov["name"],
                        "x_um":               fov["x"],
                        "z_offset_um":        fov["z_offset"],
                        "timepoint_index":    t_idx,
                        "timepoint_interval_s": self.interval_s,
                        "channel_name":       ch_name,
                        "channel_preset":     ch["preset"],
                        "channel_source":     ch["source"],
                        "channel_power_pct":  ch_power,
                        "channel_exposure_ms": ch["exposure"],
                    }
                    power_end = ch.get("power_end", 0)
                    if power_end > 0 and power_end != ch["power"]:
                        ch_meta_base["power_ramp_start_pct"] = ch["power"]
                        ch_meta_base["power_ramp_end_pct"]   = power_end

                    if self.quadrant_zs is not None:
                        # Tiled Z: snap each quadrant at its own best-Z, stitch
                        try:
                            img, n = self._snap_tiled(self.quadrant_zs)
                            if img is not None:
                                count += n
                                self.progress.emit(count, self._total, fov["name"], ch_name)
                                self.frame.emit(img)
                                fname = f"t{t_idx:04d}_{fov['name']}_{ch_name}_tiled.tiff"
                                rows, cols = self.quadrant_zs.shape
                                meta = {**ch_meta_base,
                                        "acquisition_type": "tiled_z",
                                        "z_quadrant_um": [
                                            [float(self.quadrant_zs[r, c]) for c in range(cols)]
                                            for r in range(rows)
                                        ]}
                                self._save_with_meta(img, os.path.join(self.out_dir, fname), meta)
                        except Exception as e:
                            self.err.emit(f"T{t_idx} {fov['name']} {ch_name} tiled: {e}")
                    else:
                        for z_idx, z_pos in enumerate(z_positions):
                            if not self._active:
                                break
                            try:
                                self.scope.set_z(z_pos)
                                self.msleep(80)
                                img = self.scope.snap()
                                count += 1
                                self.progress.emit(count, self._total, fov["name"], ch_name)
                                self.frame.emit(img)
                                if self.zstack:
                                    fname = (f"t{t_idx:04d}_{fov['name']}_"
                                             f"{ch_name}_z{z_idx:03d}.tiff")
                                else:
                                    fname = f"t{t_idx:04d}_{fov['name']}_{ch_name}.tiff"
                                meta = {**ch_meta_base,
                                        "acquisition_type": "zstack" if self.zstack else "timelapse",
                                        "z_um":        float(z_pos),
                                        "z_slice_index": z_idx}
                                self._save_with_meta(img, os.path.join(self.out_dir, fname), meta)
                            except Exception as e:
                                self.err.emit(
                                    f"T{t_idx} {fov['name']} {ch_name} z{z_idx}: {e}"
                                )

                        # Return to FOV base Z after each channel's stack
                        if self.zstack:
                            try:
                                self.scope.set_z(fov_z)
                            except Exception:
                                pass

                # ── Periodic channels for this FOV ────────────────────────────
                for pch in self.periodic_channels:
                    if not self._active:
                        break
                    if t_idx % max(1, pch["every_n"]) != 0:
                        continue
                    try:
                        self.scope.set_channel_full(
                            pch["preset"], pch["source"], pch["power"], pch["exposure"]
                        )
                        self.msleep(50)
                        img = self.scope.snap()
                        count += 1
                        self.progress.emit(count, self._total, fov["name"], pch["name"])
                        self.frame.emit(img)
                        fname = f"t{t_idx:04d}_{fov['name']}_{pch['name']}_periodic.tiff"
                        meta = {
                            "acquisition_type":    "periodic",
                            "fov_name":            fov["name"],
                            "x_um":                fov["x"],
                            "z_um":                float(fov_z),
                            "timepoint_index":     t_idx,
                            "timepoint_interval_s": self.interval_s,
                            "channel_name":        pch["name"],
                            "channel_preset":      pch["preset"],
                            "channel_source":      pch["source"],
                            "channel_power_pct":   pch["power"],
                            "channel_exposure_ms": pch["exposure"],
                            "every_n_timepoints":  pch["every_n"],
                        }
                        self._save_with_meta(img, os.path.join(self.out_dir, fname), meta)
                    except Exception as e:
                        self.err.emit(f"T{t_idx} {fov['name']} periodic {pch['name']}: {e}")

        try:
            self.scope.set_channel_off()
        except Exception:
            pass
        self.done.emit(count)

    def _af_sweep(self, positions: list) -> tuple:
        """Single Z sweep for inline autofocus. Returns (scores, z_visited)."""
        scores, zs = [], []
        for z in positions:
            if not self._active:
                return [], []
            try:
                self.scope.set_z(float(z))
                self.msleep(self.autofocus["settle"])
                img   = self.scope.snap()
                score = AutofocusWorker._score(img)
                scores.append(score)
                zs.append(float(z))
            except Exception:
                pass
        return scores, zs

    def _inline_autofocus(self, center_z: float, half: float) -> float | None:
        """Two-pass autofocus returning best Z, or None on failure."""
        step = self.autofocus["step"]

        coarse_pos      = list(np.arange(center_z - half, center_z + half + step * 0.5, step))
        scores, zs      = self._af_sweep(coarse_pos)
        if not scores:
            return None

        bi           = int(np.argmax(scores))
        best_coarse  = zs[bi]

        fine_step = max(0.1, step / 4.0)
        fine_pos  = list(np.arange(best_coarse - step * 2,
                                   best_coarse + step * 2 + fine_step * 0.5,
                                   fine_step))
        fine_s, fine_z = self._af_sweep(fine_pos)
        if fine_s:
            bi2    = int(np.argmax(fine_s))
            best_z = AutofocusWorker._parabolic(fine_z, fine_s, bi2)
        else:
            best_z = AutofocusWorker._parabolic(zs, scores, bi)

        try:
            self.scope.set_z(best_z)
            self.msleep(self.autofocus["settle"])
        except Exception:
            pass
        return best_z

    @staticmethod
    @staticmethod
    def _save_with_meta(img: np.ndarray, path: str, meta: dict):
        meta = dict(meta)   # shallow copy — don't mutate caller's dict
        meta["timestamp_utc"] = datetime.now(timezone.utc).isoformat()
        meta["image_height"]  = int(img.shape[0]) if img.ndim >= 2 else 0
        meta["image_width"]   = int(img.shape[1]) if img.ndim >= 2 else 0
        meta["dtype"]         = str(img.dtype)
        meta_str = json.dumps(meta, indent=2)
        try:
            import tifffile
            tifffile.imwrite(path, img, description=meta_str)
        except ImportError:
            np.save(path.replace(".tiff", ".npy"), img)
        try:
            with open(path.replace(".tiff", ".json"), "w") as f:
                f.write(meta_str)
        except Exception:
            pass

    def stop(self):
        self._active = False
        self.wait(5000)


