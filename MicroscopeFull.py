class FocusCurveWidget(QWidget):
    """Draws a live focus score vs Z position curve during autofocus sweep."""

    def __init__(self):
        super().__init__()
        self._scores:    list[float] = []
        self._positions: list[float] = []
        self._phases:    list[str]   = []
        self._best_idx: int = -1
        self.setFixedHeight(70)
        self.setStyleSheet(f"background-color: {PANEL}; border-radius: 4px;")

    def add_point(self, z: float, score: float, phase: str = "coarse"):
        self._scores.append(score)
        self._positions.append(z)
        self._phases.append(phase)
        self.update()

    def mark_best(self, best_idx: int):
        self._best_idx = best_idx
        self.update()

    def mark_best_z(self, z: float):
        if self._positions:
            self._best_idx = int(np.argmin(np.abs(np.array(self._positions) - z)))
            self.update()

    def reset(self):
        self._scores.clear()
        self._positions.clear()
        self._phases.clear()
        self._best_idx = -1
        self.update()

    def paintEvent(self, event):
        p = QPainter(self)
        p.setRenderHint(QPainter.RenderHint.Antialiasing)
        w, h, pad = self.width(), self.height(), 6

        if len(self._scores) < 2:
            p.setPen(QColor(MUTED))
            p.setFont(QFont("Segoe UI", 9))
            p.drawText(self.rect(), Qt.AlignmentFlag.AlignCenter, "Focus curve will appear here")
            return

        scores = np.array(self._scores, dtype=float)
        mn, mx = scores.min(), scores.max()
        rng    = mx - mn if mx > mn else 1.0

        def px(i):  return pad + (i / (len(scores) - 1)) * (w - 2 * pad)
        def py(v):  return h - pad - ((v - mn) / rng) * (h - 2 * pad)

        # Curve — blue for coarse sweep, cyan for fine refinement
        for i in range(1, len(scores)):
            color = CYAN if (i < len(self._phases) and self._phases[i] == "fine") else BLUE
            p.setPen(QPen(QColor(color), 1.5))
            p.drawLine(int(px(i - 1)), int(py(scores[i - 1])),
                       int(px(i)),     int(py(scores[i])))

        # Best point
        if 0 <= self._best_idx < len(scores):
            p.setPen(Qt.PenStyle.NoPen)
            p.setBrush(QColor(GREEN))
            bx, by = int(px(self._best_idx)), int(py(scores[self._best_idx]))
            p.drawEllipse(bx - 4, by - 4, 8, 8)


