    def _start(self):
        fovs     = self._fov_list()
        channels = self._active_channels()
        out_dir  = self._out_edit.text().strip()

        if not any(f["enabled"] for f in fovs):
            QMessageBox.warning(self, "No Positions", "Add at least one position.")
            return
        if not channels:
            QMessageBox.warning(self, "No Channels", "Select at least one channel.")
            return
        if not out_dir:
            QMessageBox.warning(self, "No Output", "Select an output folder.")
            return

        self._prog.setValue(0)
        self._stat.setText("Running...")
        self._stat.setStyleSheet(f"color: {YELLOW}; font-size: 11px; background: transparent;")
        self._run_btn.setText("Stop")
        self._run_btn.setStyleSheet(f"""
            QPushButton {{
                background-color: {RED}; color: {PANEL};
                border: none; border-radius: 6px;
                padding: 5px 14px; font-weight: 600;
            }}
            QPushButton:hover {{ background-color: {RED}cc; }}
        """)

        zstack = (
            {"range": self._zs_range.value(), "step": self._zs_step.value()}
            if self._zstack_cb.isChecked() else None
        )

        autofocus = (
            {
                "range":    self._af_range.value(),
                "step":     self._af_step.value(),
                "settle":   self._af_settle.value(),
                "adaptive": self._af_adaptive_cb.isChecked(),
            }
            if self._af_cb.isChecked() else None
        )

        quadrant_zs = (
            self._quadrant_zs
            if self._tile_cb.isChecked() and self._quadrant_zs is not None
            else None
        )

        self._worker = AcquisitionWorker(
            self.scope,
            self._n_timepoints(),
            self._interval.value() * 60,
            fovs, channels,
            self.scope.get_z(),
            out_dir,
            zstack=zstack,
            autofocus=autofocus,
            quadrant_zs=quadrant_zs,
            periodic_channels=self._periodic_channels(),
        )
        self._worker.progress.connect(self._on_progress)
        self._worker.frame.connect(self.sig_preview.emit)
        self._worker.done.connect(self._on_done)
        self._worker.err.connect(self.sig_log.emit)
        self._worker.start()

    def _on_progress(self, done: int, total: int, fov: str, ch: str):
        pct = int(done / max(total, 1) * 100)
        self._prog.setValue(pct)
        self._stat.setText(f"T {done}/{total}  ·  {fov}  ·  {ch}")
        self.sig_status.emit(f"Acquiring: {fov} — {ch}  ({done}/{total})")

    def _on_done(self, count: int):
        self._prog.setValue(100)
        self._stat.setText(f"Done — {count} images saved")
        self._stat.setStyleSheet(f"color: {GREEN}; font-size: 11px; background: transparent;")
        self._run_btn.setText("Run Acquisition")
        self._run_btn.setStyleSheet(f"""
            QPushButton {{
                background-color: {PURPLE}; color: {TEXT};
                border: none; border-radius: 6px;
                padding: 5px 14px; font-weight: 600;
            }}
            QPushButton:hover {{ background-color: {PURPLE}cc; }}
        """)
        self.sig_status.emit(f"Acquisition complete — {count} images saved")


