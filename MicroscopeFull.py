    def _on_connected(self):
        self._poller = PositionPoller(self.scope)
        self._poller.updated.connect(self._update_positions)
        self._poller.start()
        self.statusBar().showMessage("Connected")

    def _on_disconnected(self):
        if self._poller:
            self._poller.stop()
            self._poller = None
        if self._live_acq:
            self._live_acq.stop()
            self._live_acq = None
        self.statusBar().showMessage("Disconnected — demo mode active")

    def _update_positions(self, x: float, y: float, z: float):
        self.stage_panel.update_positions(x, z)
        self._pos_x.setText(f"{x:>10.3f}")
        self._pos_z.setText(f"{z:>10.3f}")
        if math.isnan(y):
            self._pos_y_widget.setVisible(False)
        else:
            self._pos_y_widget.setVisible(True)
            self._pos_y.setText(f"{y:>10.3f}")

    def _snap(self):
        try:
            self.image_view.set_image(self.scope.snap())
        except Exception as e:
            self.statusBar().showMessage(f"Snap error: {e}")

    def _on_af_started(self):
        self._af_was_live = self._live_acq is not None
        if self._af_was_live:
            self.cam_panel.set_live(False)

    def _on_af_stopped(self):
        if self._af_was_live:
            self.cam_panel.set_live(True)
        self._af_was_live = False

    def _toggle_live(self, on: bool):
        if on:
            self._live_acq = LiveAcquirer(self.scope)
            self._live_acq.frame.connect(self._on_frame)
            self._live_acq.start()
        elif self._live_acq:
            self._live_acq.stop()
            self._live_acq = None
            self._fps_lbl.setText("")

    def _on_frame(self, img: np.ndarray):
        self.image_view.set_image(img)
        now = time.time()
        self._frame_ts.append(now)
        self._frame_ts = [t for t in self._frame_ts if now - t < 2]
        self._fps_lbl.setText(f"{len(self._frame_ts) / 2:.1f} fps")

    def _toggle_auto(self, on: bool):
        self.image_view.auto_contrast = on
        self._auto_btn.setText("Auto Contrast  ✓" if on else "Auto Contrast")

    def closeEvent(self, event):
        if self._poller:   self._poller.stop()
        if self._live_acq: self._live_acq.stop()
        if self.acq_panel._worker: self.acq_panel._worker.stop()
        if self.af_panel._worker:    self.af_panel._worker.stop()
        if self.af_panel._fs_worker: self.af_panel._fs_worker.stop()
        event.accept()


