class LiveAcquirer(QThread):
    frame = pyqtSignal(object)

    def __init__(self, scope):
        super().__init__()
        self.scope   = scope
        self._active = True

    def run(self):
        if self.scope.connected:
            self._run_hardware()
        else:
            self._run_demo()

    def _run_hardware(self):
        """Continuous sequence acquisition — shutter stays open, no flashing."""
        core = self.scope.core
        try:
            core.clear_circular_buffer()
            core.start_continuous_sequence_acquisition(0)
            while self._active:
                if core.get_remaining_image_count() > 0:
                    t   = core.pop_next_tagged_image()
                    img = np.reshape(t.pix, [t.tags["Height"], t.tags["Width"]])
                    self.frame.emit(img)
                else:
                    self.msleep(10)
        except Exception:
            pass
        finally:
            try:
                core.stop_sequence_acquisition()
            except Exception:
                pass

    def _run_demo(self):
        while self._active:
            try:
                self.frame.emit(self.scope.snap())
            except Exception:
                pass
            self.msleep(50)

    def stop(self):
        self._active = False
        self.wait(2000)


