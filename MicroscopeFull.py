REACTOR_HOOKS = {
    "pinch_get":   None,   # () -> bool
    "pinch_toggle": None,  # () -> None
    "ch0_get":     None,   # () -> str
    "ch0_set":     None,   # (str) -> None
}


class ReactorControlsPanel(QGroupBox):
    """Bioreactor actuators surfaced beside the microscope view: the pinch valve
    (packet byte 35) and the auxiliary CH0 motor (byte 53).

    These mirror the Control Panel widgets in the main application — Qt allows a
    widget in only one layout, so this holds its own instances and stays in sync
    through REACTOR_HOOKS in both directions."""

    def __init__(self):
        super().__init__("REACTOR CONTROLS")
        lay = QVBoxLayout(self)
        lay.setContentsMargins(12, 16, 12, 12)
        lay.setSpacing(8)

        self.pinch_btn = QPushButton("Pinch State: False")
        self.pinch_btn.clicked.connect(self._toggle_pinch)
        lay.addWidget(self.pinch_btn)

        row = QHBoxLayout()
        row.setSpacing(8)
        lbl = QLabel("Aux motor CH0:")
        lbl.setStyleSheet(f"color: {MUTED}; background: transparent;")
        self.ch0_edit = QLineEdit()
        self.ch0_edit.setPlaceholderText("0-255")
        self.ch0_edit.setFixedWidth(90)
        self.ch0_edit.textChanged.connect(self._ch0_changed)
        row.addWidget(lbl)
        row.addStretch()
        row.addWidget(self.ch0_edit)
        lay.addLayout(row)

        hint = QLabel("Mirrors the reactor Control Panel; applies to the selected reactor.")
        hint.setWordWrap(True)
        hint.setStyleSheet(f"color: {MUTED}; font-size: 11px; background: transparent;")
        lay.addWidget(hint)

        if not any(REACTOR_HOOKS.values()):
            self.hide()            # standalone microscope run: nothing to control

    def _toggle_pinch(self):
        fn = REACTOR_HOOKS.get("pinch_toggle")
        if fn:
            fn()
        self.refresh()

    def _ch0_changed(self):
        fn = REACTOR_HOOKS.get("ch0_set")
        if fn:
            fn(self.ch0_edit.text())

    def refresh(self):
        """Pull current state from the reactor (signals blocked: no ping-pong)."""
        g = REACTOR_HOOKS.get("pinch_get")
        if g:
            self.pinch_btn.setText("Pinch State: " + str(bool(g())))
        c = REACTOR_HOOKS.get("ch0_get")
        if c:
            v = str(c())
            if v != self.ch0_edit.text():
                self.ch0_edit.blockSignals(True)
                self.ch0_edit.setText(v)
                self.ch0_edit.blockSignals(False)
        if any(REACTOR_HOOKS.values()):
            self.show()


