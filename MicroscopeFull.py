class MultiSnapWorker(QThread):
    frame_ready = pyqtSignal(object, str)   # img array, channel label
    saved       = pyqtSignal(str)           # path of each saved file
    done        = pyqtSignal()

    def __init__(self, scope, channels: list, orig_exposure: int, out_dir: str = ""):
        super().__init__()
        self.scope         = scope
        self.channels      = channels    # list of {'cfg', 'label', 'exposure'}
        self.orig_exposure = orig_exposure
        self.out_dir       = out_dir

    def run(self):
        # Create the next snap_N subfolder if a save dir is set
        snap_dir = ""
        if self.out_dir:
            n = 0
            while os.path.exists(os.path.join(self.out_dir, f"snap_{n}")):
                n += 1
            snap_dir = os.path.join(self.out_dir, f"snap_{n}")
            os.makedirs(snap_dir, exist_ok=True)

        for ch in self.channels:
            try:
                self.scope.set_channel(ch["cfg"])
                self.scope.set_exposure(ch["exposure"])
                self.msleep(80)
                img = self.scope.snap()
                self.frame_ready.emit(img, ch["label"])
                if snap_dir:
                    path = os.path.join(snap_dir, f"{ch['label']}.tiff")
                    meta = {
                        "acquisition_type":    "snap",
                        "channel_name":        ch["label"],
                        "channel_preset":      ch["cfg"],
                        "channel_exposure_ms": ch["exposure"],
                        "timestamp_utc":       datetime.now(timezone.utc).isoformat(),
                        "image_height":        int(img.shape[0]) if img.ndim >= 2 else 0,
                        "image_width":         int(img.shape[1]) if img.ndim >= 2 else 0,
                        "dtype":               str(img.dtype),
                    }
                    try:
                        meta["z_um"] = float(self.scope.get_z())
                        meta["x_um"] = float(self.scope.get_x())
                    except Exception:
                        pass
                    meta_str = json.dumps(meta, indent=2)
                    try:
                        import tifffile
                        tifffile.imwrite(path, img, description=meta_str)
                    except ImportError:
                        np.save(path.replace(".tiff", ".npy"), img)
                    try:
                        with open(path.replace(".tiff", ".json"), "w") as f:
                            f.write(meta_str)
                    except Exception:
                        pass
                    self.saved.emit(path)
            except Exception:
                pass
        try:
            self.scope.set_channel_off()
            self.scope.set_exposure(self.orig_exposure)
        except Exception:
            pass
        self.done.emit()


class AutofocusWorker(QThread):
    total_steps = pyqtSignal(int)
    progress    = pyqtSignal(int, float, float, str)  # step, z, score, phase
    frame       = pyqtSignal(object)                  # each captured image
    finished    = pyqtSignal(float, float)
    aborted     = pyqtSignal()
    err         = pyqtSignal(str)

    def __init__(self, scope, z_start: float, z_end: float, z_step: float,
                 settle_ms: int, two_pass: bool = True):
        super().__init__()
        self.scope      = scope
        self.z_start    = z_start
        self.z_end      = z_end
        self.z_step     = z_step
        self.settle_ms  = settle_ms
        self.two_pass   = two_pass
        self._active    = True

    def run(self):
        try:
            self._run_inner()
        except Exception as e:
            self.err.emit(f"Autofocus error: {e}")
            self.aborted.emit()

    def _run_inner(self):
        # Record start Z so we can restore it if the user stops or something fails
        try:
            start_z = float(self.scope.get_z())
        except Exception:
            start_z = (self.z_start + self.z_end) / 2.0

        coarse    = list(np.arange(self.z_start, self.z_end + self.z_step * 0.5, self.z_step))
        fine_step = max(0.1, self.z_step / 4.0)
        n_fine    = (int(self.z_step * 4.0 / fine_step) + 1) if self.two_pass else 0
        self.total_steps.emit(len(coarse) + n_fine)

        # ── Coarse pass ───────────────────────────────────────────────────────
        scores, z_visited = self._scan(coarse, "coarse", 0)

        if scores is None:          # user pressed Stop
            self._go(start_z)
            self.aborted.emit()
            return

        if not scores:              # every snap threw an exception
            self._go(start_z)
            self.err.emit("AF: all coarse snaps failed — check camera/stage connection")
            self.aborted.emit()
            return

        best_idx      = int(np.argmax(scores))
        best_z_coarse = z_visited[best_idx]

        # ── Diagnostics ───────────────────────────────────────────────────────
        # Peak at range edge → the true peak is probably outside the search range
        if best_idx == 0 or best_idx == len(scores) - 1:
            self.err.emit(
                f"AF warning: peak at range edge (step {best_idx + 1}/{len(scores)}) — "
                "try widening the search range"
            )

        # Flat curve → no real peak found (dark frame, no contrast, or settle too short)
        score_spread = max(scores) - min(scores)
        if max(scores) > 0 and score_spread / max(scores) < 0.15:
            self.err.emit(
                "AF warning: focus curve is flat (peak/min ratio < 15%) — "
                "sample may lack contrast, or settle time is too short"
            )

        if not self.two_pass:
            best_z = self._parabolic(z_visited, scores, best_idx)
            self._go(best_z)
            self.finished.emit(best_z, float(scores[best_idx]))
            return

        # ── Fine pass — quarter-step around coarse peak ───────────────────────
        fine_half = self.z_step * 2.0
        fine_pos  = list(np.arange(
            best_z_coarse - fine_half,
            best_z_coarse + fine_half + fine_step * 0.5,
            fine_step,
        ))
        fine_s, fine_z = self._scan(fine_pos, "fine", len(coarse))

        if fine_s is None:          # user pressed Stop during fine pass
            self._go(start_z)
            self.aborted.emit()
            return

        if not fine_s:
            best_z = self._parabolic(z_visited, scores, best_idx)
        else:
            bi     = int(np.argmax(fine_s))
            best_z = self._parabolic(fine_z, fine_s, bi)

        self._go(best_z)
        all_s = scores + (fine_s or [])
        self.finished.emit(best_z, float(max(all_s)))

    def _scan(self, positions: list, phase: str, offset: int):
        """Sweep positions, emitting progress. Returns (None, None) on abort."""
        scores, z_visited = [], []
        for i, z in enumerate(positions):
            if not self._active:
                return None, None
            img = None
            try:
                self.scope.set_z(float(z))
                self.msleep(self.settle_ms)
                img = self.scope.snap()
            except Exception as e:
                self.err.emit(f"AF {phase} z={z:.2f}: {e}")
                continue
            # Score and signal emission are outside the hardware try-except so
            # failures here are not silently swallowed
            score = self._score(img)
            scores.append(float(score))
            z_visited.append(float(z))
            self.frame.emit(img)
            self.progress.emit(offset + i, float(z), float(score), phase)
        return scores, z_visited

    def _go(self, z: float):
        try:
            self.scope.set_z(z)
        except Exception:
            pass

    @staticmethod
    def _score(img: np.ndarray) -> float:
        """Laplacian variance — robust focus metric for fluorescence and phase contrast."""
        try:
            f = np.asarray(img, dtype=np.float32)
            if f.ndim == 3:
                f = f.mean(axis=2)      # collapse colour channels if present
            if f.ndim != 2 or f.shape[0] < 3 or f.shape[1] < 3:
                return 0.0
            lap = (f[1:-1, 1:-1] * -4
                   + f[:-2, 1:-1] + f[2:, 1:-1]
                   + f[1:-1, :-2] + f[1:-1, 2:])
            v = float(np.var(lap))
            return v if np.isfinite(v) else 0.0
        except Exception:
            return 0.0

    @staticmethod
    def _parabolic(z_vals: list, scores: list, best_idx: int) -> float:
        """Sub-step Z precision via 3-point parabolic interpolation around peak."""
        if 0 < best_idx < len(scores) - 1:
            s1, s2, s3 = scores[best_idx - 1], scores[best_idx], scores[best_idx + 1]
            z2, z3     = z_vals[best_idx],     z_vals[best_idx + 1]
            denom = s1 - 2 * s2 + s3
            if abs(denom) > 1e-10:
                offset = 0.5 * (s1 - s3) / denom
                return float(z2 + offset * (z3 - z2))
        return float(z_vals[best_idx])

    def stop(self):
        self._active = False
        self.wait(5000)


class FocusStackWorker(QThread):
    """
    Acquires a Z-stack, scores each quadrant of each slice, then assembles a
    composite image by stitching the sharpest-focus crop from each quadrant.
    Borders are cross-faded so there are no hard seams.
    """
    progress  = pyqtSignal(int, int)                  # slices_done, total_slices
    finished  = pyqtSignal(object, float, object)     # composite, median_z, best_z array (rows×cols)
    aborted   = pyqtSignal()

    def __init__(self, scope, z_start: float, z_end: float, z_step: float,
                 settle_ms: int, grid: tuple = (2, 2)):
        super().__init__()
        self.scope     = scope
        self.z_start   = z_start
        self.z_end     = z_end
        self.z_step    = z_step
        self.settle_ms = settle_ms
        self.grid      = grid          # (rows, cols)
        self._active   = True

    def run(self):
        positions = list(np.arange(self.z_start, self.z_end + self.z_step * 0.5, self.z_step))
        stack: list[tuple[float, np.ndarray]] = []

        # ── Acquire Z-stack ───────────────────────────────────────────────────
        for i, z in enumerate(positions):
            if not self._active:
                self.aborted.emit()
                return
            try:
                self.scope.set_z(float(z))
                self.msleep(self.settle_ms)
                img = self.scope.snap()
                stack.append((float(z), img))
                self.progress.emit(i + 1, len(positions))
            except Exception:
                pass

        if len(stack) < 2:
            self.aborted.emit()
            return

        # ── Per-quadrant best-focus index map ─────────────────────────────────
        rows, cols = self.grid
        H, W = stack[0][1].shape
        qh   = H // rows
        qw   = W // cols

        best_idx = np.zeros((rows, cols), dtype=int)
        best_z   = np.zeros((rows, cols), dtype=float)

        for r in range(rows):
            for c in range(cols):
                y0, y1 = r * qh, min((r + 1) * qh, H)
                x0, x1 = c * qw, min((c + 1) * qw, W)
                scores = [
                    AutofocusWorker._score(img[y0:y1, x0:x1])
                    for _, img in stack
                ]
                bi             = int(np.argmax(scores))
                best_idx[r, c] = bi
                best_z[r, c]   = stack[bi][0]

        # ── Stitch composite with soft border blend ────────────────────────────
        composite  = self._blend(stack, best_idx, rows, cols, H, W, qh, qw)
        median_z   = float(np.median(best_z))
        try:
            self.scope.set_z(median_z)
        except Exception:
            pass

        self.finished.emit(composite, median_z, best_z)

    @staticmethod
    def _blend(stack, best_idx, rows, cols, H, W, qh, qw, blend_frac: float = 0.20):
        """Stitch quadrant crops with a linear cross-fade at shared borders."""
        images   = [img.astype(np.float32) for _, img in stack]
        out_f    = np.zeros((H, W), dtype=np.float32)
        weight_f = np.zeros((H, W), dtype=np.float32)
        blend_h  = max(1, int(qh * blend_frac))
        blend_w  = max(1, int(qw * blend_frac))

        for r in range(rows):
            for c in range(cols):
                y0, y1 = r * qh, min((r + 1) * qh, H)
                x0, x1 = c * qw, min((c + 1) * qw, W)
                img    = images[best_idx[r, c]]

                wy = np.ones(y1 - y0, dtype=np.float32)
                wx = np.ones(x1 - x0, dtype=np.float32)

                if r > 0:
                    b = min(blend_h, len(wy))
                    wy[:b] = np.linspace(0.0, 1.0, b)
                if r < rows - 1:
                    b = min(blend_h, len(wy))
                    wy[-b:] = np.linspace(1.0, 0.0, b)
                if c > 0:
                    b = min(blend_w, len(wx))
                    wx[:b] = np.linspace(0.0, 1.0, b)
                if c < cols - 1:
                    b = min(blend_w, len(wx))
                    wx[-b:] = np.linspace(1.0, 0.0, b)

                w = np.outer(wy, wx)
                out_f[y0:y1, x0:x1]    += img[y0:y1, x0:x1] * w
                weight_f[y0:y1, x0:x1] += w

        np.divide(out_f, np.maximum(weight_f, 1e-6), out=out_f)
        return out_f.astype(stack[0][1].dtype)

    def stop(self):
        self._active = False
        self.wait(5000)


